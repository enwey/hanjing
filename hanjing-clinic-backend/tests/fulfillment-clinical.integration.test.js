import { test } from 'node:test';
import assert from 'node:assert/strict';
import mysql from 'mysql2/promise';
import express from 'express';
import jwt from 'jsonwebtoken';

test('fulfillment clinical details stay linked to the billed consultation', async (t) => {
  // A dedicated temporary schema: never seed or mutate the running business database.
  const schema = 'hanjing_test_fulfillment_' + Date.now();
  const admin = await mysql.createConnection({ host: '127.0.0.1', port: 3306,
    user: process.env.TEST_DB_USER || 'root', password: process.env.TEST_DB_PASSWORD || 'root' });
  let db, server;
  await admin.query('CREATE DATABASE ' + schema);
  try {
    Object.assign(process.env, { DB_HOST: '127.0.0.1', DB_PORT: '3306', DB_NAME: schema,
      DB_USER: process.env.TEST_DB_USER || 'root', DB_PASSWORD: process.env.TEST_DB_PASSWORD || 'root' });
    db = await import('../db.js');
    await db.initDB();
    const { resolveFulfillmentMedicalRecord, readFulfillmentClinical } = await import('../fulfillment-clinical.js');
    await admin.query('USE ' + schema);
    await admin.query("INSERT INTO users(id,openid,nickname) VALUES(1,'TEST-FULFILLMENT','Test')");
    await admin.query("INSERT INTO patients(id,user_id,name,relation) VALUES(1,1,'Test patient','self'),(2,1,'Other patient','child')");
    await admin.query("INSERT INTO doctors(id,name,title,specialty) VALUES(1,'Doctor','Title','Sleep')");
    await admin.query("INSERT INTO stores(id,name,code,address) VALUES(1,'Clinic','TEST','Test address')");
    await admin.query("INSERT INTO doctor_schedules(id,doctor_id,store_id,date,period,start_time,end_time) VALUES(1,1,1,'2026-01-01','morning','09:00','12:00')");
    await admin.query("INSERT INTO ess_assessments(id,user_id,patient_id,total_score,risk_level,answers) VALUES(1,1,1,12,'medium','[]')");
    await admin.query("INSERT INTO snore_assessments(id,user_id,patient_id,file_url,duration,avg_decibel,peak_decibel,snore_rate,apnea_events) VALUES(1,1,1,'/test',600,50,80,30,2)");
    await admin.query("INSERT INTO appointments(id,appointment_no,user_id,patient_id,store_id,doctor_id,schedule_id,appointment_date,appointment_time,symptom_desc,ess_assessment_id,snore_assessment_id) VALUES(1,'TEST-A',1,1,1,1,1,'2026-01-01','09:00','Test symptom',1,1)");
    await admin.query("INSERT INTO appointment_pre_exams(appointment_id,height,weight,bmi) VALUES(1,170,65,22.5)");
    await admin.query("INSERT INTO medical_records(id,patient_id,doctor_id,store_id,appointment_id,visit_date,diagnosis,prescription,doctor_advice,note,created_at) VALUES(1,1,1,1,1,'2026-01-01','Original diagnosis','Original prescription','Original advice','Original note','2026-01-01 10:00'),(2,1,1,1,NULL,'2026-02-01','Later diagnosis','Later prescription',NULL,NULL,'2026-02-01 10:00')");
    await admin.query("INSERT INTO treatment_records(id,patient_id,doctor_id,medical_record_id,device_model,device_product_name,initial_advancement,start_date) VALUES(1,1,1,1,'Device A','Original device',0,'2026-01-01'),(2,1,1,2,'Device B','Later device',5,'2026-02-01')");
    await admin.query("INSERT INTO patient_devices(id,patient_id,bind_treatment_record_id,bind_medical_record_id,device_model,initial_advancement,bound_at) VALUES(1,1,1,1,'Device A',0,'2026-01-01'),(2,1,2,2,'Device B',5,'2026-02-01')");
    await admin.query('UPDATE treatment_records SET patient_device_id=id');
    await admin.query("INSERT INTO orders(id,order_no,user_id,total_amount,pay_amount,appointment_id,status,pay_at,shipping_address) VALUES(1,'TEST-O1',1,100,100,1,'paid',NOW(),JSON_OBJECT('storeId',1)),(2,'TEST-O2',1,100,100,NULL,'paid',NOW(),JSON_OBJECT('storeId',1))");
    const originalCase = { patient_id: 1, order_id: 1, store_id: 1, medical_record_id: 1, created_at: '2026-03-01 10:00:00' };
    await t.test('exact record supplies prescription, bound device, zero initial setting and complete screening', async () => {
      const data = await readFulfillmentClinical(originalCase);
      assert.equal(data.medical_record.prescription, 'Original prescription');
      assert.equal(data.medical_record.doctor_advice, 'Original advice');
      assert.equal(data.medical_record.note, 'Original note');
      assert.equal(data.treatments.length, 1);
      assert.equal(data.treatments[0].device_product_name, 'Original device');
      assert.equal(data.treatments[0].patient_device.id, 1);
      assert.equal(Number(data.treatments[0].initial_advancement), 0);
      assert.equal(data.appointment.symptom_desc, 'Test symptom');
      assert.equal(Number(data.pre_exam.height), 170);
      assert.equal(data.ess_report.total_score, 12);
      assert.equal(data.snore_report.apnea_events, 2);
    });
    await t.test('order appointment remains authoritative when a newer consultation exists', async () => {
      assert.equal((await resolveFulfillmentMedicalRecord({ ...originalCase, medical_record_id: null })).id, 1);
    });
    await t.test('ambiguous legacy data and cross-patient record IDs never select an unrelated latest record', async () => {
      assert.equal(await resolveFulfillmentMedicalRecord({ ...originalCase, order_id: 2, medical_record_id: null }), null);
      assert.equal(await resolveFulfillmentMedicalRecord({ ...originalCase, patient_id: 2 }), null);
      assert.equal((await resolveFulfillmentMedicalRecord({ ...originalCase, order_id: 2, medical_record_id: null, created_at: '2026-01-02 10:00:00' })).id, 1);
    });
    await t.test('a follow-up adjustment links its existing device to that consultation', async () => {
      await admin.query("INSERT INTO medical_records(id,patient_id,doctor_id,store_id,visit_date,diagnosis,prescription) VALUES(3,1,1,1,'2026-03-01','Review','Adjust original device')");
      await admin.query("INSERT INTO device_adjustments(treatment_id,patient_device_id,medical_record_id,adjust_date,operator_id,adjusted_advancement,patient_feedback,instructions) VALUES(1,1,3,'2026-03-01',1,2,'Comfortable','Advance to 2 mm')");
      const data = await readFulfillmentClinical({ ...originalCase, medical_record_id: 3 });
      assert.equal(data.treatments.length, 1);
      assert.equal(data.treatments[0].id, 1);
      assert.equal(data.treatments[0].adjustments[0].instructions, 'Advance to 2 mm');
      assert.equal(data.treatments[0].adjustments[0].medical_record_id, 3);
    });
    await t.test('schema changes are safe to run repeatedly', async () => {
      await db.closePool();
      await db.initDB();
      assert.equal((await readFulfillmentClinical(originalCase)).medical_record.id, 1);
    });
    await t.test('technician can read full details without system permission; products exclude services', async () => {
      await admin.query("INSERT INTO roles(id,name,code) VALUES(100,'Test technician','test_technician')");
      await admin.query("INSERT INTO permissions(role_id,permission_resource) VALUES(100,'order:view')");
      await admin.query("INSERT INTO admin_users(id,username,password_hash,name,role_id) VALUES(100,'test-tech','unused','Technician',100)");
      await admin.query('INSERT INTO admin_user_stores(admin_user_id,store_id) VALUES(100,1)');
      await admin.query("INSERT INTO products(id,name,category,image_url,price) VALUES(100,'Device product','device','/test',100),(101,'Consultation','service','/test',20)");
      await admin.query("INSERT INTO order_items(order_id,product_id,product_name,product_image,price,quantity) VALUES(1,100,'Device snapshot','/test',100,1),(1,101,'Consultation snapshot','/test',20,1)");
      await admin.query('INSERT INTO fulfillment_cases(id,order_id,patient_id,store_id,technician_id,created_by,medical_record_id) VALUES(1,1,1,1,100,100,1)');
      const router = (await import('../routes/admin.js')).default;
      const { JWT_SECRET } = await import('../helpers.js');
      const app = express();
      app.use(express.json(), router);
      server = await new Promise(resolve => { const s = app.listen(0, '127.0.0.1', () => resolve(s)); });
      const base = `http://127.0.0.1:${server.address().port}`;
      const headers = { Authorization: 'Bearer ' + jwt.sign({ id: 100, role: 'test_technician' }, JWT_SECRET, { expiresIn: '1m' }) };
      const list = await fetch(base + '/api/admin/fulfillment/cases', { headers }).then(r => r.json());
      assert.equal(list.code, 200);
      assert.equal(list.data[0].device_product_names, 'Device snapshot ×1');
      assert.equal(list.data[0].prescription, 'Original prescription');
      const detail = await fetch(base + '/api/admin/fulfillment/cases/1/detail', { headers }).then(r => r.json());
      assert.equal(detail.code, 200);
      assert.equal(detail.data.medical_record.id, 1);
      assert.equal(detail.data.patient.id, 1);
      assert.ok(Array.isArray(detail.data.follow_ups));
      assert.equal(detail.data.items.length, 2);
      const staff = await fetch(base + '/api/admin/fulfillment/technicians', { headers }).then(r => r.json());
      assert.deepEqual(staff.data, [{ id: 100, name: 'Technician' }]);
      assert.equal((await fetch(base + '/api/admin/admin-users', { headers })).status, 403);
      assert.equal((await fetch(base + '/api/admin/fulfillment/cases/1/assign', { method: 'POST', headers })).status, 403);
      assert.equal((await fetch(base + '/api/admin/fulfillment/cases/1/detail')).status, 401);
      await admin.query('DELETE FROM admin_user_stores WHERE admin_user_id=100');
      assert.equal((await fetch(base + '/api/admin/fulfillment/cases/1/detail', { headers })).status, 404);
    });
    await t.test('mold drafts, batch locking, shipping snapshots, partial returns and retakes form one workflow', async () => {
      await admin.query('INSERT INTO admin_user_stores(admin_user_id,store_id) VALUES(100,1)');
      await admin.query("INSERT INTO permissions(role_id,permission_resource) VALUES(100,'order:edit')");
      await admin.query("UPDATE fulfillment_cases SET status='assigned' WHERE id=1");
      await admin.query("INSERT INTO fulfillment_cases(id,order_id,patient_id,store_id,technician_id,created_by,medical_record_id,status) VALUES(2,2,1,1,100,100,1,'assigned')");
      const { JWT_SECRET } = await import('../helpers.js');
      const token = jwt.sign({id:100,role:'test_technician'},JWT_SECRET,{expiresIn:'20m'});
      const base=`http://127.0.0.1:${server.address().port}/api/admin/fulfillment`;
      const headers={Authorization:'Bearer '+token,'Content-Type':'application/json'};
      const call=async(path,method='GET',body,expected=200)=>{
        const r=await fetch(base+path,{method,headers,body:body===undefined?undefined:JSON.stringify(body)});
        const json=await r.json();assert.equal(r.status,expected,`${method} ${path}: ${JSON.stringify(json)}`);return json.data;
      };
      const details=(no,date='2026-10-07')=>({mold_no:no,storage_location:'A-01',taken_date:date,method:'实体口模',parameters:[{name:'前移量',value:'0',unit:'mm'}],wear_hours:8,wear_period:'夜间',adaptation:'按医生要求适应',requirements:'按口模定制',note:'制作备注',file_ids:[]});
      await call('/cases/1/mold','POST',{revision:0,complete:true,details:{...details('M1'),wear_hours:25}},400);
      await call('/cases/1/mold','POST',{revision:0,complete:true,details:{...details('M1'),parameters:[]}},400);
      const file=await call('/cases/1/mold-files','POST',{name:'test.stl',base64:Buffer.from('solid test\nendsolid test').toString('base64')});
      const fileRes=await fetch(base+`/cases/1/mold-files/${file.id}`,{headers});assert.equal(fileRes.status,200);assert.match(fileRes.headers.get('content-disposition'),/attachment/);
      await call(`/cases/2/mold-files/${file.id}`,'GET',undefined,404);
      await call('/cases/2/mold','POST',{revision:0,complete:true,details:{...details('M2'),file_ids:[file.id]}},400);
      const draft={revision:0,complete:false,details:{...details('M1'),file_ids:[file.id]}};
      const race=await Promise.all([1,2].map(()=>fetch(base+'/cases/1/mold',{method:'POST',headers,body:JSON.stringify(draft)}).then(r=>r.status)));
      assert.deepEqual(race.sort(),[200,409]);
      assert.equal((await call('/ready-molds')).length,0);
      await call('/cases/1/mold','POST',{...draft,revision:1,complete:true});
      await call('/cases/2/mold','POST',{revision:0,complete:true,details:details('M2','2026-10-06')});
      assert.equal((await call('/ready-molds?date=2026-10-07')).length,1);
      assert.equal((await call('/ready-molds')).length,2);
      await call('/cases/1/mold-shipment','POST',{carrier:'快递',tracking_no:'OLD'},409);
      const batchRace=await Promise.all([1,2].map(()=>fetch(base+'/batches',{method:'POST',headers,body:JSON.stringify({factory_name:'Test factory',case_ids:[1]})}).then(async r=>({status:r.status,data:(await r.json()).data}))));
      assert.deepEqual(batchRace.map(r=>r.status).sort(),[200,409]);
      await call(`/batches/${batchRace.find(r=>r.status===200).data.id}/cancel`,'POST',{});
      assert.equal((await call('/ready-molds')).length,2);
      const batch=await call('/batches','POST',{factory_name:'Test factory',case_ids:[2,1]});
      assert.equal((await call('/cases/1/mold')).editable,false);
      await call('/cases/1/mold','POST',{...draft,revision:2,complete:true},409);
      await call(`/batches/${batch.id}/ship`,'POST',{carrier:'Test carrier',tracking_no:'TRACK'},400);
      await call(`/batches/${batch.id}/ship`,'POST',{carrier:'Test carrier',tracking_no:'TRACK',confirmed:true});
      await call(`/batches/${batch.id}/ship`,'POST',{carrier:'Test carrier',tracking_no:'TRACK',confirmed:true},409);
      await call(`/batches/${batch.id}/cancel`,'POST',{},409);
      const shipped=await call(`/batches/${batch.id}`);
      assert.equal(shipped.items.length,2);
      assert.equal(shipped.items[0].snapshot.mold.parameters[0].value,'0');
      assert.equal(shipped.items[0].snapshot.files[0].id,file.id);
      assert.equal(shipped.items[0].snapshot.prescription,'Original prescription');
      assert.ok(!Object.keys(shipped.items[0].snapshot).includes('patient_name'));
      await admin.query("UPDATE medical_records SET prescription='Changed after shipment' WHERE id=1");
      assert.deepEqual((await call(`/batches/${batch.id}`)).items.map(i=>i.snapshot),shipped.items.map(i=>i.snapshot));
      await call('/cases/1/mold-files','POST',{name:'new.stl',base64:'dGVzdA=='},409);
      const receipt={device_serial_no:'DEVICE-1',storage_location:'B-01'};
      await call('/cases/1/device-receipt','POST',receipt,409);
      const first=shipped.items.find(i=>i.fulfillment_case_id===1),second=shipped.items.find(i=>i.fulfillment_case_id===2);
      const progress=(item,action,feedback='')=>call(`/batches/${batch.id}/items/${item.id}/progress`,'POST',{action,feedback});
      await progress(first,'received');await progress(first,'producing');await progress(first,'exception','边缘需调整');
      await call('/cases/1/device-receipt','POST',receipt,409);
      await progress(first,'producing','工厂已处理');
      await call('/cases/1/device-receipt','POST',{...receipt,inspection_result:'failed'},400);
      await call('/cases/1/device-receipt','POST',receipt);
      await call('/cases/1/device-receipt','POST',receipt,409);
      await call('/cases/1/assign','POST',{technician_id:100},409);
      await call('/cases/1/notify-fitting','POST',{});
      await call('/cases/1/notify-fitting','POST',{},400);
      await call('/cases/1/fitting','POST',{patient_device_id:1,note:'试戴完成'});
      await call('/cases/1/fitting','POST',{patient_device_id:1},400);
      assert.equal((await db.get('SELECT COUNT(*) AS n FROM fulfillment_fittings WHERE fulfillment_case_id=1')).n,1);
      const partial=await call(`/batches/${batch.id}`);
      assert.equal(partial.items.find(i=>i.id===first.id).status,'returned');
      assert.equal(partial.items.find(i=>i.id===first.id).receipt.device_serial_no,'DEVICE-1');
      assert.equal(partial.items.find(i=>i.id===first.id).receipt.storage_location,'B-01');
      assert.equal(partial.items.find(i=>i.id===second.id).status,'shipped');
      assert.equal((await call('/batches')).find(b=>b.id===batch.id).returned_count,1);
      await progress(second,'retake','口模损坏，需要重取');
      const retake=await call('/cases/2/mold');assert.equal(retake.profile.mold_id,null);assert.equal(retake.editable,true);
      await call('/cases/2/mold','POST',{revision:retake.profile.revision,complete:true,details:details('M2-RETAKE')});
      const redo=await call('/batches','POST',{factory_name:'Test factory',case_ids:[2]});
      await call(`/batches/${redo.id}/ship`,'POST',{carrier:'Test carrier',tracking_no:'TRACK-REDO',confirmed:true});
      assert.equal((await call(`/batches/${batch.id}`)).items.find(i=>i.id===second.id).snapshot.mold.mold_no,'M2');
      assert.equal((await call(`/batches/${redo.id}`)).items[0].snapshot.mold.mold_no,'M2-RETAKE');
      await admin.query('DELETE FROM admin_user_stores WHERE admin_user_id=100');
      assert.equal((await call('/batches')).length,0);
      await call(`/batches/${batch.id}`,'GET',undefined,404);
      await call(`/batches/${redo.id}/items/1/progress`,'POST',{action:'received'},404);
      await admin.query('INSERT INTO admin_user_stores(admin_user_id,store_id) VALUES(100,1)');
      if(process.env.DELIVERY_BROWSER_TEST==='1') {
        await admin.query("INSERT INTO orders(id,order_no,user_id,total_amount,pay_amount,appointment_id) VALUES(998,'TEST-BROWSER',1,100,100,1)");
        await admin.query("INSERT INTO fulfillment_cases(id,order_id,patient_id,store_id,technician_id,created_by,medical_record_id,status) VALUES(998,998,1,1,100,100,1,'assigned')");
        const {verifyDeliveryBrowser}=await import('./delivery-browser.js');
        await verifyDeliveryBrowser({base:`http://127.0.0.1:${server.address().port}`,token});
      }
    });
  } finally {
    if (server) await new Promise(resolve => server.close(resolve));
    if (db) await db.closePool();
    assert.match(schema, /^hanjing_test_fulfillment_[0-9]+$/);
    await admin.query('DROP DATABASE ' + schema);
    await admin.end();
  }
});
